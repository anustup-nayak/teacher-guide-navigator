// Publish the website's lesson catalogs from the pinned content releases (content/website.json):
// each release's views/v1/catalog.mjs is verified against its manifest hash, then copied to its
// dist/ path. It also writes dist/day-types.mjs (day type and label of every teaching day, from
// each release's structure.json) so the website never keeps its own copy of the program
// structure. `--check` writes nothing and fails if dist/ differs from the pinned releases.
//
// Usage: node scripts/content/publish_site.mjs [--check]
import fs from 'node:fs';
import crypto from 'node:crypto';
import {pathToFileURL} from 'node:url';

const ROOT = new URL('../../', import.meta.url);
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');

export function pinnedCatalogs() {
  const {packs} = JSON.parse(fs.readFileSync(new URL('content/website.json', ROOT)));
  return Object.entries(packs).map(([pack, {version, catalog}]) => {
    const release = new URL(`content/${pack}/${version}/`, ROOT);
    const manifest = JSON.parse(fs.readFileSync(new URL('manifest.json', release)));
    const source = new URL('views/v1/catalog.mjs', release), bytes = fs.readFileSync(source);
    const expected = manifest.files?.['views/v1/catalog.mjs']?.sha256 ?? manifest.files?.['views/v1/catalog.mjs'];
    if (expected !== sha256(bytes)) throw new Error(`${pack} ${version}: views/v1/catalog.mjs does not match its manifest hash`);
    return {pack, version, bytes, target: new URL(`dist/${catalog}`, ROOT), catalog};
  });
}

// Short card label: the day type's name without a quoted instrument name
// (‘साप्ताहिक आकलन ‘मैंने सीख लिया’’ → ‘साप्ताहिक आकलन’). Teaching days get no label.
const shortName = name => name.replace(/\s*‘[^’]*’\s*$/u, '').trim();
export function dayTypesModule() {
  const {packs} = JSON.parse(fs.readFileSync(new URL('content/website.json', ROOT)));
  const out = {};
  for (const [pack, {version}] of Object.entries(packs)) {
    const release = new URL(`content/${pack}/${version}/`, ROOT);
    const manifest = JSON.parse(fs.readFileSync(new URL('manifest.json', release)));
    const bytes = fs.readFileSync(new URL('structure.json', release));
    if (manifest.files['structure.json']?.sha256 !== sha256(bytes)) throw new Error(`${pack} ${version}: structure.json does not match its manifest hash`);
    const structure = JSON.parse(bytes);
    out[pack] = {version,
      types: Object.fromEntries(structure.dayTypes.map(t => [t.id, {purpose: t.purpose,
        label: t.purpose === 'new-skills' ? null : {hi: shortName(t.name.hi), en: shortName(t.name.en ?? t.name.hi)}}])),
      calendar: structure.calendar.filter(b => b.cycle).map(b => [b.grade, b.from, b.to, b.cycle.map(r => [r.days, r.dayType])])};
  }
  return `// Generated by scripts/content/publish_site.mjs from the pinned content releases. Do not edit.\nexport const DAY_TYPES=${JSON.stringify(out)};\n`;
}

// Program-guide data (docs/PROGRAM_GUIDE_DESIGN.md, slice A): per grade, the calendar, day types,
// period outline and the guide's section page map, from each pinned release's hash-checked
// structure.json and sections.json. Source pages are kept per grade so every screen can open them.
function releaseJson(pack, version, file) {
  const release = new URL(`content/${pack}/${version}/`, ROOT);
  const manifest = JSON.parse(fs.readFileSync(new URL('manifest.json', release)));
  const bytes = fs.readFileSync(new URL(file, release));
  if (manifest.files[file]?.sha256 !== sha256(bytes)) throw new Error(`${pack} ${version}: ${file} does not match its manifest hash`);
  return JSON.parse(bytes);
}
// Goals for a grade with the lessons that build them. Only links the website may show: stated, or
// derived/editorial ones that are reviewed or owner-approved (the query library's default policy).
const SHOWABLE = l => l.assertion === 'stated' || ['reviewed', 'owner-approved'].includes(l.review);
function goalLinks(pack, version) {
  const goals = releaseJson(pack, version, 'entities/goal.json');
  if (!goals.length) return {goals: [], lessonGoals: {}};
  const outcomes = new Map(releaseJson(pack, version, 'entities/lo.json').map(o => [o.id, o]));
  const lessons = releaseJson(pack, version, 'entities/lesson.json');
  const lessonGoals = {};
  const full = goals.filter(g => SHOWABLE(g.provenance)).sort((a, b) => a.grade - b.grade || a.order - b.order).map(g => {
    const codes = g.outcomes.filter(SHOWABLE).map(l => l.to.slice(3));
    const members = lessons.filter(l => l.grade === g.grade && (l.outcomes || []).some(o => SHOWABLE(o) && codes.includes(o.to.slice(3))))
      .sort((a, b) => a.week - b.week || a.day - b.day)
      .map(l => ({id: l.id, week: l.week, day: l.day, stated: l.outcomes.some(o => o.assertion === 'stated' && codes.includes(o.to.slice(3)))}));
    for (const m of members) (lessonGoals[m.id] ??= []).push(g.id);
    return {id: g.id, grade: g.grade, order: g.order, title: g.title,
      outcomes: codes.map(c => ({code: c, statement: outcomes.get(c)?.statement ?? ''})), lessons: members};
  });
  return {goals: full, lessonGoals};
}
const goalCache = new Map();
const goalsOf = (pack, version) => { if (!goalCache.has(pack)) goalCache.set(pack, goalLinks(pack, version)); return goalCache.get(pack); };
const goalsFor = (pack, version, grade) => goalsOf(pack, version).goals.filter(g => g.grade === grade);
export function lessonGoalsModule() {
  const {packs} = JSON.parse(fs.readFileSync(new URL('content/website.json', ROOT)));
  const out = {};
  for (const [pack, {version}] of Object.entries(packs)) {
    const {goals, lessonGoals} = goalsOf(pack, version);
    if (goals.length) out[pack] = {titles: Object.fromEntries(goals.map(g => [g.id, g.title])), lessons: lessonGoals};
  }
  return `// Generated by scripts/content/publish_site.mjs from the pinned content releases. Do not edit.\nexport const LESSON_GOALS=${JSON.stringify(out)};\n`;
}
const SHOWN = new Set(['program', 'article', 'assessment', 'routines', 'resources', 'resource', 'tracker']);
export function programGuideModule() {
  const {packs} = JSON.parse(fs.readFileSync(new URL('content/website.json', ROOT)));
  const out = {};
  for (const [pack, {version}] of Object.entries(packs)) {
    const structure = releaseJson(pack, version, 'structure.json'), sections = releaseJson(pack, version, 'sections.json');
    const grades = {};
    for (const [g, guide] of Object.entries(sections.guides)) {
      const grade = Number(g), doc = guide.document;
      const pages = prov => (prov?.sources || []).filter(r => r.doc === doc).map(r => r.pdf);
      grades[g] = {
        doc,
        calendar: structure.calendar.filter(b => b.grade === grade).map(b => ({from: b.from, to: b.to, kind: b.kind,
          ...(b.label ? {label: b.label} : {}), ...(b.cycle ? {cycle: b.cycle.map(r => [r.days, r.dayType])} : {}), ...(b.plan ? {plan: b.plan.pdf} : {})})),
        dayTypes: Object.fromEntries(structure.dayTypes.filter(t => t.grades.includes(grade)).map(t => [t.id, {
          name: t.name, purpose: t.purpose, planForm: t.planForm,
          short: t.purpose === 'new-skills' ? null : {hi: shortName(t.name.hi), en: shortName(t.name.en ?? t.name.hi)},
          periods: t.periods.map(p => ({number: p.number, role: p.role, ...(p.minutes ? {minutes: p.minutes} : {}),
            slots: (p.slots || []).map(x => ({name: x.name, kind: x.kind, ...(x.minutes ? {minutes: x.minutes} : {})}))})),
          sequence: (t.sequence || []).map(x => ({name: x.name, kind: x.kind})),
          pages: pages(t.provenance)}])),
        periods: structure.periodOutline.filter(o => o.grade === grade).map(o => ({number: o.number, minutes: o.minutes, role: o.role, focus: o.focus, pages: pages(o.provenance)})),
        sections: guide.sections.filter(x => SHOWN.has(x.kind)).map(x => ({id: x.id, kind: x.kind, title: x.title, pdf: x.pdf})),
        goals: goalsFor(pack, version, grade)
      };
    }
    out[pack] = {version, printedOffset: sections.printedOffset ?? 2, grades};
  }
  return `// Generated by scripts/content/publish_site.mjs from the pinned content releases. Do not edit.\nexport const PROGRAM_GUIDE=${JSON.stringify(out)};\n`;
}

export function publishSite({check = false} = {}) {
  const results = [];
  const dayTypes = Buffer.from(dayTypesModule()), dayTarget = new URL('dist/day-types.mjs', ROOT);
  const daySame = fs.existsSync(dayTarget) && fs.readFileSync(dayTarget).equals(dayTypes);
  if (!daySame && check) throw new Error('dist/day-types.mjs differs from the pinned releases');
  if (!daySame) fs.writeFileSync(dayTarget, dayTypes);
  results.push(`day types → dist/day-types.mjs: ${daySame ? 'identical' : 'published'}`);
  const guide = Buffer.from(programGuideModule()), guideTarget = new URL('dist/program-guide-data.mjs', ROOT);
  const guideSame = fs.existsSync(guideTarget) && fs.readFileSync(guideTarget).equals(guide);
  if (!guideSame && check) throw new Error('dist/program-guide-data.mjs differs from the pinned releases');
  if (!guideSame) fs.writeFileSync(guideTarget, guide);
  results.push(`program guide → dist/program-guide-data.mjs: ${guideSame ? 'identical' : 'published'}`);
  const lg = Buffer.from(lessonGoalsModule()), lgTarget = new URL('dist/lesson-goals.mjs', ROOT);
  const lgSame = fs.existsSync(lgTarget) && fs.readFileSync(lgTarget).equals(lg);
  if (!lgSame && check) throw new Error('dist/lesson-goals.mjs differs from the pinned releases');
  if (!lgSame) fs.writeFileSync(lgTarget, lg);
  results.push(`lesson goals → dist/lesson-goals.mjs: ${lgSame ? 'identical' : 'published'}`);
  for (const c of pinnedCatalogs()) {
    const current = fs.existsSync(c.target) ? fs.readFileSync(c.target) : null;
    const same = current?.equals(c.bytes) ?? false;
    if (!same && check) throw new Error(`dist/${c.catalog} differs from ${c.pack} release ${c.version}`);
    if (!same) fs.writeFileSync(c.target, c.bytes);
    results.push(`${c.pack} ${c.version} → dist/${c.catalog}: ${same ? 'identical' : 'published'}`);
  }
  return results;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const line of publishSite({check: process.argv.includes('--check')})) console.log(line);
}

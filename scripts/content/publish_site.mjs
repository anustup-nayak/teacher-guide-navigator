// Publish the website's lesson catalogs from the pinned content releases (content/website.json):
// each release's views/v1/catalog.mjs is verified against its manifest hash, then copied to its
// dist/ path. It also writes dist/day-types.mjs (day type and label of every teaching day, from
// each release's structure.json) so the website never keeps its own copy of the program
// structure. `--check` writes nothing and fails if dist/ differs from the pinned releases.
//
// Usage: node scripts/content/publish_site.mjs [--check]
import fs from 'node:fs';
import crypto from 'node:crypto';
import {pathToFileURL} from 'node:url';

const ROOT = new URL('../../', import.meta.url);
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');

export function pinnedCatalogs() {
  const {packs} = JSON.parse(fs.readFileSync(new URL('content/website.json', ROOT)));
  return Object.entries(packs).map(([pack, {version, catalog}]) => {
    const release = new URL(`content/${pack}/${version}/`, ROOT);
    const manifest = JSON.parse(fs.readFileSync(new URL('manifest.json', release)));
    const source = new URL('views/v1/catalog.mjs', release), bytes = fs.readFileSync(source);
    const expected = manifest.files?.['views/v1/catalog.mjs']?.sha256 ?? manifest.files?.['views/v1/catalog.mjs'];
    if (expected !== sha256(bytes)) throw new Error(`${pack} ${version}: views/v1/catalog.mjs does not match its manifest hash`);
    return {pack, version, bytes, target: new URL(`dist/${catalog}`, ROOT), catalog};
  });
}

// Short card label: the day type's name without a quoted instrument name
// (‘साप्ताहिक आकलन ‘मैंने सीख लिया’’ → ‘साप्ताहिक आकलन’). Teaching days get no label.
const shortName = name => name.replace(/\s*‘[^’]*’\s*$/u, '').trim();
export function dayTypesModule() {
  const {packs} = JSON.parse(fs.readFileSync(new URL('content/website.json', ROOT)));
  const out = {};
  for (const [pack, {version}] of Object.entries(packs)) {
    const release = new URL(`content/${pack}/${version}/`, ROOT);
    const manifest = JSON.parse(fs.readFileSync(new URL('manifest.json', release)));
    const bytes = fs.readFileSync(new URL('structure.json', release));
    if (manifest.files['structure.json']?.sha256 !== sha256(bytes)) throw new Error(`${pack} ${version}: structure.json does not match its manifest hash`);
    const structure = JSON.parse(bytes);
    out[pack] = {version,
      types: Object.fromEntries(structure.dayTypes.map(t => [t.id, {purpose: t.purpose,
        label: t.purpose === 'new-skills' ? null : {hi: shortName(t.name.hi), en: shortName(t.name.en ?? t.name.hi)}}])),
      calendar: structure.calendar.filter(b => b.cycle).map(b => [b.grade, b.from, b.to, b.cycle.map(r => [r.days, r.dayType])])};
  }
  return `// Generated by scripts/content/publish_site.mjs from the pinned content releases. Do not edit.\nexport const DAY_TYPES=${JSON.stringify(out)};\n`;
}

export function publishSite({check = false} = {}) {
  const results = [];
  const dayTypes = Buffer.from(dayTypesModule()), dayTarget = new URL('dist/day-types.mjs', ROOT);
  const daySame = fs.existsSync(dayTarget) && fs.readFileSync(dayTarget).equals(dayTypes);
  if (!daySame && check) throw new Error('dist/day-types.mjs differs from the pinned releases');
  if (!daySame) fs.writeFileSync(dayTarget, dayTypes);
  results.push(`day types → dist/day-types.mjs: ${daySame ? 'identical' : 'published'}`);
  for (const c of pinnedCatalogs()) {
    const current = fs.existsSync(c.target) ? fs.readFileSync(c.target) : null;
    const same = current?.equals(c.bytes) ?? false;
    if (!same && check) throw new Error(`dist/${c.catalog} differs from ${c.pack} release ${c.version}`);
    if (!same) fs.writeFileSync(c.target, c.bytes);
    results.push(`${c.pack} ${c.version} → dist/${c.catalog}: ${same ? 'identical' : 'published'}`);
  }
  return results;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const line of publishSite({check: process.argv.includes('--check')})) console.log(line);
}
